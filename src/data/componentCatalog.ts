interface Def {
  id: string;
  label: string;
  category: ComponentCategoryId;
  icon: string;
  shape?: NodeShape;
  description: string;
  name?: string;
  w?: number;
  h?: number;
  meta?: MetadataField[];
}

const def = (d: Def): ComponentTypeDef => ({
  id: d.id,
  label: d.label,
  category: d.category,
  icon: d.icon,
  shape: d.shape ?? 'box',
  description: d.description,
  defaultName: d.name ?? d.label,
  size: { width: d.w ?? 180, height: d.h ?? 84 },
  metadataFields: d.meta ?? [],
});

